// node tools/beats-src.mjs
// Turns the editorial choices in tools/beats-picks.json into shell/js/ui/beats-src.js.
// The passages are copied from read/data/text/aNN.json by block index, so no sentence of the book
// is ever retyped. Run it from the repo root after changing the picks or the texts.
import fs from 'node:fs';
import { ARTICLES } from '../assets/js/data.js';

const picks = JSON.parse(fs.readFileSync('tools/beats-picks.json', 'utf8'));
const pad2 = (n) => String(n).padStart(2, '0');
const len = (s) => [...s].length;
// Footnote marks point at notes that DIVE does not show. Superscript digits are dropped everywhere;
// a mark printed as a plain digit is listed per article in the picks ("fix": [[from, to]]) and must
// match exactly once, so nothing else can be changed by accident.
const unmarked = (s) => s.replace(/[¹²³⁰-⁹]+/g, "");
const STAT_AT = {};
const SRC = {};
const LIGHT = {};
const problems = [];
const notes = [];

for (const a of ARTICLES) {
  const p = picks[a.no];
  if (!p) {
    notes.push(`${pad2(a.no)}: no picks (the stop shows the digest without passages; every number waits in 框架)`);
    continue;
  }
  const text = JSON.parse(fs.readFileSync(`read/data/text/a${pad2(a.no)}.json`, 'utf8'));
  const where = `article ${pad2(a.no)}`;
  const fixed = new Map(); // fix -> in how many passages it matched

  if (!Array.isArray(p.statAt) || p.statAt.length !== a.stats.length) problems.push(`${where}: statAt needs ${a.stats.length} entries`);
  else if (p.statAt.some((b) => !Number.isInteger(b) || b < 1 || b > 5)) problems.push(`${where}: statAt entries are 1-5`);
  else STAT_AT[a.no] = p.statAt;

  if (!Array.isArray(p.src) || p.src.length !== 6) {
    problems.push(`${where}: src needs six lists (beats 0-5)`);
  } else {
    const seen = new Set();
    SRC[a.no] = p.src.map((list, beat) => {
      let chars = 0;
      const out = list.map((i) => {
        const b = text.blocks[i];
        if (!b) problems.push(`${where} beat ${beat}: block ${i} does not exist`);
        else if (b.t !== 'p' && b.t !== 'q') problems.push(`${where} beat ${beat}: block ${i} is a heading`);
        if (seen.has(i)) problems.push(`${where} beat ${beat}: block ${i} is used twice`);
        seen.add(i);
        let x = b ? unmarked(b.x) : '';
        for (const [from, to] of p.fix || []) {
          if (x.includes(from)) {
            if (x.split(from).length !== 2) problems.push(`${where} beat ${beat}: "${from}" matches more than once`);
            x = x.replace(from, to);
            fixed.set(from, (fixed.get(from) || 0) + 1);
          }
        }
        chars += len(x);
        return x;
      });
      if (chars > 340) notes.push(`${where} beat ${beat}: ${chars} characters under one beat (long)`);
      return out;
    });
  }

  for (const [from] of p.fix || []) {
    const n = fixed.get(from) || 0;
    if (n !== 1) problems.push(`${where}: fix "${from}" matches ${n ? `in ${n} passages` : 'nothing'}`);
  }

  if (Number.isInteger(p.light) && p.light >= 0) {
    if (p.light >= a.stats.length) problems.push(`${where}: light points past the numbers`);
    else LIGHT[a.no] = p.light;
  }
}

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const out = `// GENERATED by tools/beats-src.mjs from tools/beats-picks.json and read/data/text/aNN.json.
// Do not edit by hand: change the picks and run the tool again.

// Which beat each of an article's numbers rides: 1-4 = the key point that states it, 5 = 框架.
export const STAT_AT = ${JSON.stringify(STAT_AT)};

// The index of the number that also stands in the scene as a figure of light (most articles: none).
export const LIGHT = ${JSON.stringify(LIGHT)};

// The article in its own words: for beats 0-5, whole paragraphs of the full text, word for word.
export const SRC = ${JSON.stringify(SRC, null, 1)};
`;
fs.writeFileSync('shell/js/ui/beats-src.js', out);
const total = Object.values(SRC).reduce((n, beats) => n + beats.flat().reduce((m, x) => m + len(x), 0), 0);
console.log(`shell/js/ui/beats-src.js: ${Object.keys(SRC).length} articles, ${total} characters of the book`);
if (notes.length) console.log(notes.join('\n'));
